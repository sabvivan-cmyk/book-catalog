function mockIsbn(id) {
  const firstTwelve = `9785000000${String(id).padStart(2, '0')}`
  const sum = [...firstTwelve].reduce((total, digit, index) => total + Number(digit) * (index % 2 ? 3 : 1), 0)
  return `${firstTwelve}${(10 - (sum % 10)) % 10}`
}

function book(id, title, year, description, authorIds, coverUrl) {
  return {
    id,
    title,
    year,
    description,
    isbn: mockIsbn(id),
    cover_url: coverUrl,
    authors: authors.filter((author) => authorIds.includes(author.id)),
  }
}

